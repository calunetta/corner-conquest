import type { MonsterName } from '@/lib/types';
import type { MonsterCatalogEntry } from './monster-catalog.types';

const MONSTER_SPRITE_DIRECTORY = '/monster';
const GENERATED_HEADER = '// Generated by scripts/generate-monster-catalog.ts. Do not edit by hand.';
// "<boss->-<slug>-lvl<N>-<idle|attack>.gif"; the level cap is enforced in parseMonsterSpriteFilename
const MIN_LEVEL = 1;
const MAX_NON_BOSS_LEVEL = 3;
const MAX_BOSS_LEVEL = 4;
const MONSTER_SPRITE_FILENAME = /^(boss-)?([a-z0-9]+(?:-[a-z0-9]+)*)-lvl(\d+)-(idle|attack)\.gif$/i;

/** The 4 permanent entries. Used whenever a scan of public/monster/ misses one of them, so
 *  every level 1-4 and the boss pool are always non-empty. */
export const SEED_MONSTER_CATALOG: MonsterCatalogEntry[] = [
  { name: 'Lancer', level: 1, isBoss: false, sprite: { idle: '/monster/lancer-lvl1-idle.gif', attack: '/monster/lancer-lvl1-attack.gif' } },
  { name: 'Bear', level: 2, isBoss: false, sprite: { idle: '/monster/bear-lvl2-idle.gif', attack: '/monster/bear-lvl2-attack.gif' } },
  { name: 'Ogre', level: 3, isBoss: false, sprite: { idle: '/monster/ogre-lvl3-idle.gif', attack: '/monster/ogre-lvl3-attack.gif' } },
  { name: 'Minotaur', level: 4, isBoss: true, sprite: { idle: '/monster/boss-minotaur-lvl4-idle.gif', attack: '/monster/boss-minotaur-lvl4-attack.gif' } },
];

export interface ParsedMonsterSpriteFile {
  /** Title Case, e.g. "Fire Ogre" for "fire-ogre-lvl2-idle.gif". */
  name: string;
  level: 1 | 2 | 3 | 4;
  isBoss: boolean;
  kind: 'idle' | 'attack';
}

function toTitleCase(slug: string): string {
  return slug
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(' ');
}

/** Returns null for any filename that is not a .gif matching the convention. Levels: non-boss 1-3, boss 1-4;
 *  a level above the cap is skipped with a console warning. */
export function parseMonsterSpriteFilename(filename: string): ParsedMonsterSpriteFile | null {
  const match = MONSTER_SPRITE_FILENAME.exec(filename);
  if (!match) return null;

  const [, bossPrefix, slug, levelText, kind] = match;
  const level = Number(levelText);
  const isBoss = bossPrefix !== undefined;
  const maxLevel = isBoss ? MAX_BOSS_LEVEL : MAX_NON_BOSS_LEVEL;
  if (level < MIN_LEVEL) return null;
  if (level > maxLevel) {
    console.warn(`Skipping ${filename}: ${isBoss ? 'boss' : 'non-boss'} monsters go up to level ${maxLevel}.`);
    return null;
  }

  return {
    name: toTitleCase(slug),
    level: level as ParsedMonsterSpriteFile['level'],
    isBoss,
    kind: kind.toLowerCase() as ParsedMonsterSpriteFile['kind'],
  };
}

const toEntryKey = (name: string, level: number): string => `${name}|${level}`;

function groupFilenamesIntoEntries(filenames: string[]): MonsterCatalogEntry[] {
  const entriesByKey = new Map<string, MonsterCatalogEntry>();
  const attackByKey = new Map<string, string>();

  for (const filename of filenames) {
    const parsed = parseMonsterSpriteFilename(filename);
    if (!parsed) continue;

    const key = toEntryKey(parsed.name, parsed.level);
    const path = `${MONSTER_SPRITE_DIRECTORY}/${filename}`;
    if (parsed.kind === 'attack') {
      attackByKey.set(key, path);
      continue;
    }
    entriesByKey.set(key, {
      // The generator is what produces the MonsterName union, so a new name cannot be typed yet.
      name: parsed.name as MonsterName,
      level: parsed.level,
      isBoss: parsed.isBoss,
      sprite: { idle: path },
    });
  }

  for (const [key, entry] of entriesByKey) {
    const attack = attackByKey.get(key);
    if (attack) entry.sprite.attack = attack;
  }
  return [...entriesByKey.values()];
}

/** Groups sprite files by name and level (idle required, attack optional) and merges in any
 *  missing seed. Order: seeds first in seed order, then newly parsed entries in filename order. */
export function buildMonsterCatalogEntries(filenames: string[]): MonsterCatalogEntry[] {
  const scanned = groupFilenamesIntoEntries(filenames);
  const scannedByKey = new Map(scanned.map((entry) => [toEntryKey(entry.name, entry.level), entry]));
  const seedKeys = new Set(SEED_MONSTER_CATALOG.map((seed) => toEntryKey(seed.name, seed.level)));

  const seeds = SEED_MONSTER_CATALOG.map((seed) => scannedByKey.get(toEntryKey(seed.name, seed.level)) ?? seed);
  const extras = scanned.filter((entry) => !seedKeys.has(toEntryKey(entry.name, entry.level)));
  return [...seeds, ...extras];
}

function renderEntry(entry: MonsterCatalogEntry): string {
  const attack = entry.sprite.attack ? `, attack: '${entry.sprite.attack}'` : '';
  return `  { name: '${entry.name}', level: ${entry.level}, isBoss: ${entry.isBoss}, sprite: { idle: '${entry.sprite.idle}'${attack} } },`;
}

/** Full text of monster-catalog.generated.ts. */
export function renderMonsterCatalogSource(entries: MonsterCatalogEntry[]): string {
  return [
    GENERATED_HEADER,
    "import type { MonsterCatalogEntry } from './monster-catalog.types';",
    '',
    'export const MONSTER_CATALOG: MonsterCatalogEntry[] = [',
    ...entries.map(renderEntry),
    '];',
    '',
  ].join('\n');
}

function toMonsterNameKey(name: string): string {
  return name.replace(/\s+/g, '');
}

/** Full text of monsters.generated.ts, over distinct names in the given order. */
export function renderMonsterNameSource(names: string[]): string {
  const distinctNames = [...new Set(names)];
  return [
    GENERATED_HEADER,
    'export const MonsterName = {',
    ...distinctNames.map((name) => `  ${toMonsterNameKey(name)}: '${name}',`),
    '} as const;',
    'export type MonsterName = (typeof MonsterName)[keyof typeof MonsterName];',
    '',
  ].join('\n');
}
